"""
unet_pack.py - makes everything the FPGA needs from the trained int8 U-Net.

Reads the golden int8 package of fpga_ref (golden_model\\data\\golden_vectors\\mem and
models\\fpga\\tiny_unet_int8.npz), then
  1. packs weights / biases / requant params into BRAM init files (hw\\mem)
  2. writes the layer table as SystemVerilog (rtl\\unet_layers_pkg.sv)
  3. runs the bit-exact hardware model (tools\\fpga_model.py) and checks EVERY conv layer
     against the golden vectors (must print 12/12 bit-exact)
  4. writes test vectors for the RTL testbenches (mem\\tb_*.mem)

    cd <repository root>
    python hw\\tools\\unet_pack.py
"""
import argparse, os, sys
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import fpga_model as fm

REPO = os.path.dirname(ROOT)                                  # repository root
PC = os.path.join(HERE, "tof_geometry")                      # ToF geometry package


def write_lines(path, lines):
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


def gen_layers_pkg(pk, path):
    L = pk.layers
    s = []
    s.append("// ============================================================================")
    s.append("// unet_layers_pkg.sv - GENERATED by tools/unet_pack.py, do not edit by hand.")
    s.append("// Layer table of the Tiny U-Net (unet_v5) for the Nexys4 DDR accelerator.")
    s.append("// Bank regions (bytes in each of the 16 banks): [0,4800) [4800,9600) [9600,12000)")
    s.append("// ============================================================================")
    s.append("`timescale 1ns/1ps")
    s.append("")
    s.append("package unet_layers_pkg;")
    s.append("")
    s.append(f"    localparam int N_LAYERS  = {len(L)};")
    s.append(f"    localparam int N_WWORDS  = {pk.weights.shape[0]};   // weight words (1024 bit)")
    s.append(f"    localparam int N_PWORDS  = {len(pk.params)};   // param words (896 bit)")
    s.append("")
    s.append("    typedef struct packed {")
    fields = [("cin", 7), ("cout", 7), ("hin", 7), ("win", 8), ("hout", 7), ("wout", 8),
              ("k3", 1), ("s2", 1), ("relu", 1), ("argmax", 1), ("src_frame", 1),
              ("n_icg", 4), ("n_ocg", 3),
              ("a_base", 14), ("a_w", 8), ("a_hw", 13), ("a_up", 1), ("a_m", 15), ("a_sh", 6), ("ca", 7),
              ("b_base", 14), ("b_w", 8), ("b_hw", 13), ("b_m", 15), ("b_sh", 6),
              ("out_base", 14), ("out_hw", 13), ("w_base", 11), ("w_per_ocg", 11), ("p_base", 5)]
    for n, w in fields:
        s.append(f"        logic [{w - 1}:0] {n};")
    s.append("    } layer_t;")
    s.append("")
    s.append("    function automatic layer_t layer_desc(input logic [3:0] idx);")
    s.append("        layer_t d;")
    s.append("        d = '0;")
    s.append("        unique case (idx)")
    for i, l in enumerate(L):
        vals = dict(cin=l.cin, cout=l.cout, hin=l.hin, win=l.win, hout=l.hout, wout=l.wout,
                    k3=l.k3, s2=l.s2, relu=l.relu, argmax=l.argmax, src_frame=l.src_frame,
                    n_icg=l.n_icg, n_ocg=l.n_ocg,
                    a_base=l.a_base, a_w=l.a_w, a_hw=l.a_hw, a_up=l.a_up, a_m=l.a_m, a_sh=l.a_sh, ca=l.ca,
                    b_base=l.b_base, b_w=l.b_w, b_hw=l.b_hw, b_m=l.b_m, b_sh=l.b_sh,
                    out_base=l.out_base, out_hw=l.hout * l.wout, w_base=l.w_base,
                    w_per_ocg=l.n_icg * l.kk, p_base=l.p_base)
        body = " ".join(f"d.{k} = {v};" for k, v in vals.items())
        s.append(f"        4'd{i}: begin  // {l.name}  -> golden {l.check}")
        s.append(f"            {body}")
        s.append("        end")
    s.append("        default: ;")
    s.append("        endcase")
    s.append("        return d;")
    s.append("    endfunction")
    s.append("")
    s.append("endpackage")
    write_lines(path, s)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pc", default=PC, help="ToF geometry package")
    a = ap.parse_args()
    gdir = os.path.join(REPO, "golden_model", "data", "golden_vectors")
    memdir = os.path.join(gdir, "mem")
    npz = np.load(os.path.join(REPO, "golden_model", "data", "model", "tiny_unet_int8_quantised.npz"))
    pk = fm.pack_network(memdir, npz["gray__s"])
    out = os.path.join(ROOT, "mem")
    os.makedirs(out, exist_ok=True)

    write_lines(os.path.join(out, "unet_weights.mem"), fm.weight_words(pk))
    write_lines(os.path.join(out, "unet_params.mem"), fm.param_words(pk))
    write_lines(os.path.join(out, "unet_inlut.mem"), ["%02x" % (int(v) & 0xFF) for v in pk.in_lut])
    gen_layers_pkg(pk, os.path.join(REPO, "rtl", "unet_layers_pkg.sv"))

    # test frame: the golden camera frame, as the ESP32-CAM will send it (160x120, 2x2 average)
    import cv2
    fp = os.path.join(gdir, "frame.png")
    if os.path.exists(fp):                                    # full-resolution source frame (not in the repository)
        frame = fm.downsample_2x2(cv2.imread(fp, cv2.IMREAD_GRAYSCALE))
    else:                                                     # the stored 160x120 test frame
        frame = fm._rd(os.path.join(out, "tb_frame.mem"), 8).reshape(120, 160).astype(np.uint8)
    q = pk.in_lut[frame.astype(np.int64)]
    qg = fm._rd(os.path.join(memdir, "input_q.mem"), 8)
    assert np.array_equal(q.ravel(), qg), "input LUT does not reproduce input_q.mem"
    write_lines(os.path.join(out, "tb_frame.mem"), ["%02x" % v for v in frame.ravel()])

    res, outs, labels = fm.check_against_golden(memdir, pk, frame)
    ok = sum(r[2] == 0 for r in res)
    for name, chk, bad in res:
        print(f"  {name:10s} vs {chk:16s} {'bit-exact' if bad == 0 else f'{bad} MISMATCHES'}")
    g = fm._rd(os.path.join(memdir, "L026_Conv_out0.mem"), 8).reshape(6, 60, 80)
    lab_ok = np.array_equal(labels, np.argmax(g, 0))
    write_lines(os.path.join(out, "tb_labels.mem"), ["%x" % v for v in labels.ravel()])
    print(f"weights {pk.weights.shape[0]} x 1024 bit, params {len(pk.params)} x 896 bit, input LUT 256 B")
    print(f"model vs golden: {ok}/{len(res)} conv layers bit-exact, label map {'bit-exact' if lab_ok else 'DIFFERS'}")
    if ok != len(res) or not lab_ok:
        sys.exit(1)
    print("wrote", out, "and rtl/unet_layers_pkg.sv")


if __name__ == "__main__":
    main()
